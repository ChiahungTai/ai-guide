@dataclass(frozen=True)
class ModelCapability:
    name: str
    evidence: str


@dataclass(frozen=True)
class ModelIdentity:
    id: str
    label: str
    capabilities: tuple[ModelCapability, ...]


@dataclass(frozen=True)
class DispatchBinding:
    id: str
    model_identity: str
    carrier: str
    surface: str
    token: str
    token_kind: str
    family: str
    effort_encoding: str
    effort_values: tuple[str, ...]
    fixed_effort: str | None
    transport: tuple[str, ...]


@dataclass(frozen=True)
class QualificationRecord:
    workload: str
    model_identity: str
    status: str
    evidence_source: str
    binding_scope: tuple[str, ...]
    minimum_effective_effort: str | None


@dataclass(frozen=True)
class ModelCatalog:
    workloads: frozenset[str]
    harness_alias_tokens: frozenset[str]
    families: frozenset[str]
    identities: dict[str, ModelIdentity]
    bindings: dict[str, DispatchBinding]
    qualifications: tuple[QualificationRecord, ...]


def _catalog_keys_ok(table: dict, allowed: frozenset[str], where: str) -> None:
    illegal = set(table) - allowed
    assert not illegal, (
        f"catalog: {where}: 鍵 {sorted(illegal)} 超出白名單 {sorted(allowed)}"
    )


def _catalog_required(table: dict, keys: tuple[str, ...], where: str) -> None:
    for key in keys:
        assert key in table, f"catalog: {where}: 缺必要鍵 {key!r}"


def _reject_forbidden_keys(node: object, path: str, forbidden: frozenset[str]) -> None:
    if isinstance(node, dict):
        for key, value in node.items():
            assert key not in forbidden, (
                f"{path.split('.')[0]}: 禁止欄位 {key!r}（volatile／demand state"
                f" 不住此源——{path}.{key}）"
            )
            _reject_forbidden_keys(value, f"{path}.{key}", forbidden)
    elif isinstance(node, list):
        for item in node:
            _reject_forbidden_keys(item, path, forbidden)


def parse_catalog(text: str) -> ModelCatalog:
    """解析＋驗證 catalog（schema／enum／token 混型／FK／唯一性／volatile 欄位）。

    任何違規＝AssertionError（caller fail loud）；通過＝可供機械查詢的
    ModelCatalog（identity／binding／qualification 供給事實）。
    """
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise AssertionError(f"catalog: TOML 語法錯誤——{exc}") from exc
    _reject_forbidden_keys(data, "catalog", _FORBIDDEN_CATALOG_KEYS)
    _catalog_keys_ok(
        data,
        frozenset(
            {
                "schema_version",
                "allow_lists",
                "model_identity",
                "dispatch_binding",
                "qualification",
            }
        ),
        "頂層",
    )
    version = data.get("schema_version")
    assert version == 1, f"catalog: schema_version {version!r}（預期 1）"
    allow = data.get("allow_lists", {})
    _catalog_keys_ok(
        allow,
        frozenset({"workloads", "harness_alias_tokens", "families"}),
        "allow_lists",
    )
    for list_key in ("workloads", "harness_alias_tokens", "families"):
        values = allow.get(list_key)
        assert (
            isinstance(values, list)
            and values
            and all(isinstance(v, str) and v for v in values)
        ), f"catalog: allow_lists.{list_key} 需非空字串清單"
        assert len(values) == len(set(values)), (
            f"catalog: allow_lists.{list_key} 有重複值"
        )
    workloads = frozenset(allow["workloads"])
    alias_tokens = frozenset(allow["harness_alias_tokens"])
    families = frozenset(allow["families"])

    # --- model_identity ---
    identities: dict[str, ModelIdentity] = {}
    identity_rows = data.get("model_identity", [])
    for row in identity_rows:
        _catalog_keys_ok(
            row, frozenset({"id", "label", "capability"}), "model_identity"
        )
        _catalog_required(row, ("id",), "model_identity")
        mid = row["id"]
        assert mid not in identities, f"catalog: duplicate model_identity id {mid!r}"
        capabilities: list[ModelCapability] = []
        cap_names: set[str] = set()
        for cap in row.get("capability", []):
            _catalog_keys_ok(cap, frozenset({"name", "evidence"}), "capability")
            _catalog_required(cap, ("name", "evidence"), "capability")
            assert cap["name"] in _CAPABILITY_NAMES, (
                f"catalog: capability name {cap['name']!r} 不在詞彙"
                f"（合法：{sorted(_CAPABILITY_NAMES)}）"
            )
            assert cap["evidence"] in _EVIDENCE_SOURCES, (
                f"catalog: capability evidence {cap['evidence']!r} 不在詞彙"
                f"（合法：{sorted(_EVIDENCE_SOURCES)}）"
            )
            assert cap["name"] not in cap_names, (
                f"catalog: model_identity {mid!r} capability {cap['name']!r} 重複"
            )
            cap_names.add(cap["name"])
            capabilities.append(ModelCapability(cap["name"], cap["evidence"]))
        identities[mid] = ModelIdentity(mid, row.get("label", mid), tuple(capabilities))

    # --- dispatch_binding ---
    bindings: dict[str, DispatchBinding] = {}
    token_scopes: set[tuple[str, str, str, str]] = set()
    for row in data.get("dispatch_binding", []):
        _catalog_keys_ok(
            row,
            frozenset(
                {
                    "id",
                    "model_identity",
                    "carrier",
                    "surface",
                    "token",
                    "token_kind",
                    "family",
                    "effort_encoding",
                    "effort_values",
                    "fixed_effort",
                    "transport",
                }
            ),
            "dispatch_binding",
        )
        _catalog_required(
            row,
            (
                "id",
                "model_identity",
                "carrier",
                "surface",
                "token",
                "token_kind",
                "family",
                "effort_encoding",
            ),
            "dispatch_binding",
        )
        bid = row["id"]
        assert bid not in bindings, f"catalog: duplicate dispatch_binding id {bid!r}"
        mid = row["model_identity"]
        assert mid in identities, (
            f"catalog: binding {bid!r} model_identity {mid!r} 未定義"
        )
        kind = row["token_kind"]
        assert kind in _TOKEN_KINDS, (
            f"catalog: unknown token_kind {kind!r}（合法：{sorted(_TOKEN_KINDS)}）"
        )
        family = row["family"]
        assert family in families, (
            f"catalog: binding {bid!r}: unknown family {family!r}"
            f"（合法：{sorted(families)}——allow_lists.families 閉集）"
        )
        token = row["token"]
        if kind == "provider_native":
            assert _PROVIDER_NATIVE_TOKEN_RE.match(token), (
                f"catalog: binding {bid!r}: provider_native token {token!r} 含非法"
                "字元或 carrier slug 形態——native/alias/slug 禁混型"
            )
        elif kind == "harness_alias":
            assert token in alias_tokens, (
                f"catalog: binding {bid!r}: harness_alias token {token!r} 不在"
                " allow_lists.harness_alias_tokens——native/alias/slug 禁混型"
            )
        else:
            assert _CARRIER_SLUG_TOKEN_RE.match(token), (
                f"catalog: binding {bid!r}: carrier_slug token {token!r} 非 carrier"
                " 限定形態（須含 '/'，如 chatgpt-web/high）——native/alias/slug 禁混型"
            )
        scope = (row["carrier"], row["surface"], kind, token)
        assert scope not in token_scopes, (
            f"catalog: duplicate token scope (carrier={row['carrier']!r}, "
            f"surface={row['surface']!r}, token_kind={kind!r}, token={token!r})"
            "——同 token 在同 carrier/surface 只能有一個 binding"
        )
        token_scopes.add(scope)
        encoding = row["effort_encoding"]
        assert encoding in _EFFORT_ENCODINGS, (
            f"catalog: binding {bid!r}: unknown effort_encoding {encoding!r}"
            f"（合法：{sorted(_EFFORT_ENCODINGS)}）"
        )
        values = tuple(row.get("effort_values", []))
        fixed = row.get("fixed_effort")
        if encoding in {"field", "param"}:
            assert values and fixed is None, (
                f"catalog: binding {bid!r} effort_encoding={encoding!r} 形態不符"
                "（slug_fixed 需 fixed_effort；field/param 需 effort_values；"
                "unsupported 兩者皆禁）"
            )
        elif encoding == "slug_fixed":
            assert fixed is not None and not values, (
                f"catalog: binding {bid!r} effort_encoding={encoding!r} 形態不符"
            )
        else:
            assert fixed is None and not values, (
                f"catalog: binding {bid!r} effort_encoding={encoding!r} 形態不符"
            )
        for value in (*values, fixed):
            if value is not None:
                assert value in _EFFORT_ORDINAL, (
                    f"catalog: binding {bid!r}: effort token {value!r} 不在"
                    f" _EFFORT_ORDINAL 跨家族詞彙（{sorted(_EFFORT_ORDINAL)}）"
                )
        transport = tuple(row.get("transport", []))
        assert set(transport) <= _TRANSPORT_CAPS, (
            f"catalog: binding {bid!r} transport {sorted(set(transport) - _TRANSPORT_CAPS)}"
            f" 不在詞彙（合法：{sorted(_TRANSPORT_CAPS)}）"
        )
        bindings[bid] = DispatchBinding(
            bid,
            mid,
            row["carrier"],
            row["surface"],
            token,
            kind,
            family,
            encoding,
            values,
            fixed,
            transport,
        )

    # --- qualification ---
    records: list[QualificationRecord] = []
    scopes_by_key: dict[tuple[str, str], list[tuple[str, ...]]] = {}
    for row in data.get("qualification", []):
        _catalog_keys_ok(
            row,
            frozenset(
                {
                    "workload",
                    "model_identity",
                    "status",
                    "evidence_source",
                    "binding_scope",
                    "minimum_effective_effort",
                }
            ),
            "qualification",
        )
        _catalog_required(
            row,
            (
                "workload",
                "model_identity",
                "status",
                "evidence_source",
                "binding_scope",
            ),
            "qualification",
        )
        workload = row["workload"]
        assert workload in workloads, (
            f"catalog: workload {workload!r} 不在 allow_lists.workloads"
            f"（合法：{sorted(workloads)}）"
        )
        mid = row["model_identity"]
        assert mid in identities, (
            f"catalog: qualification({workload},{mid}) model_identity 未定義"
        )
        status = row["status"]
        assert status in _QUAL_STATUSES, (
            f"catalog: qualification status {status!r} 不在詞彙"
            f"（合法：{sorted(_QUAL_STATUSES)}）；availability 禁入 status/evidence 欄"
        )
        evidence = row["evidence_source"]
        assert evidence in _EVIDENCE_SOURCES, (
            f"catalog: evidence_source {evidence!r} 不在詞彙"
            f"（合法：{sorted(_EVIDENCE_SOURCES)}）；availability 禁入 status/evidence 欄"
        )
        scope = tuple(row["binding_scope"])
        assert scope, "catalog: qualification binding_scope 不可為空"
        for scoped_id in scope:
            if scoped_id == "*":
                continue
            assert scoped_id in bindings, (
                f"catalog: qualification({workload},{mid}) scope 引用不存在的"
                f" binding {scoped_id!r}"
            )
            owner = bindings[scoped_id].model_identity
            assert owner == mid, (
                f"catalog: qualification({workload},{mid}) scope binding"
                f" {scoped_id!r} 屬 model_identity {owner!r} 非 {mid!r}"
            )
        key = (workload, mid)
        for existing in scopes_by_key.get(key, []):
            assert not ("*" in existing or "*" in scope or existing == scope), (
                f"catalog: qualification({workload},{mid}) scope 重疊——同"
                " (workload, model_identity) 的 scope 禁互疊（'*' 含一切）"
            )
        scopes_by_key.setdefault(key, []).append(scope)
        minimum = row.get("minimum_effective_effort")
        if minimum is not None:
            assert minimum in _EFFORT_ORDINAL, (
                f"catalog: minimum_effective_effort {minimum!r} 不在跨家族詞彙"
                f"（{sorted(_EFFORT_ORDINAL)}）"
            )
            if status == "qualified":
                scoped_bindings = (
                    [b for b in bindings.values() if b.model_identity == mid]
                    if "*" in scope
                    else [bindings[sid] for sid in scope]
                )
                assert any(
                    b.effort_encoding != "unsupported" for b in scoped_bindings
                ), (
                    f"catalog: qualification({workload},{mid}) status=qualified 帶"
                    " minimum_effective_effort，但 scope 內無 binding 可確認"
                    " effective effort——此形態只能 conditional（不滿足 decision"
                    " hard gate）"
                )
        records.append(
            QualificationRecord(workload, mid, status, evidence, scope, minimum)
        )

    return ModelCatalog(
        workloads, alias_tokens, families, identities, bindings, tuple(records)
    )


def load_catalog(repo: Path) -> ModelCatalog:
    """讀取 repo 的 catalog（缺檔＝FileNotFoundError——caller 先驗存在性）。"""
    return parse_catalog((repo / CATALOG_SOURCE).read_text(encoding="utf-8"))


# --- 供給面機械查詢（無 demand 知識；resolver 語義歸 model-routing skill）---


def effective_effort(
    binding: DispatchBinding, requested_effort: str | None
) -> str | None:
    """binding 對 effective effort 的確認結果（None＝無法確認，fail-closed）。"""
    if binding.effort_encoding == "slug_fixed":
        return binding.fixed_effort
    if binding.effort_encoding == "unsupported":
        return None
    if requested_effort is not None and requested_effort in binding.effort_values:
        return requested_effort
    return None


def qualification_for(
    catalog: ModelCatalog, workload: str, binding: DispatchBinding
) -> QualificationRecord | None:
    """適用於 (workload, binding) 的記錄（scope 命中；載入時已保證至多一筆）。"""
    for rec in catalog.qualifications:
        if (
            rec.workload == workload
            and rec.model_identity == binding.model_identity
            and ("*" in rec.binding_scope or binding.id in rec.binding_scope)
        ):
            return rec
    return None


def direct_visual_eligible(catalog: ModelCatalog, binding: DispatchBinding) -> bool:
    """direct visual eligibility＝ModelIdentity.native_vision ∩ binding.image_transport。"""
    identity = catalog.identities.get(binding.model_identity)
    native = identity is not None and any(
        cap.name == "native_vision" for cap in identity.capabilities
    )
    return native and "image_transport" in binding.transport


def passes_decision_hard_gate(
    catalog: ModelCatalog,
    workload: str,
    binding: DispatchBinding,
    requested_effort: str | None,
) -> bool:
    """decision hard gate（機械層）：status=qualified 且（如有 minimum）effective
    effort 可確認且達標。conditional／無記錄／effort 無法確認——皆不過 gate；
    effort 不能把未 qualification 的 candidate 補成 decision-qualified。
    """
    rec = qualification_for(catalog, workload, binding)
    if rec is None or rec.status != "qualified":
        return False
    if rec.minimum_effective_effort is None:
        return True
    effort = effective_effort(binding, requested_effort)
    return effort is not None and (
        _EFFORT_ORDINAL[effort] >= _EFFORT_ORDINAL[rec.minimum_effective_effort]
    )


