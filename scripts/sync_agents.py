def parse_presets(text: str) -> dict[str, Preset]:
    """解析＋驗證 presets（schema／enum／forbidden 欄位／membership 一致性）。

    任何違規＝AssertionError（caller fail loud）；FK 到 catalog 的部分在
    resolve_deployment 驗（parse 無 catalog 知識）。
    """
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise AssertionError(f"presets: TOML 語法錯誤——{exc}") from exc
    _reject_forbidden_keys(data, "presets", _FORBIDDEN_PRESET_KEYS)
    _catalog_keys_ok(
        data, frozenset({"schema_version", "allow_lists", "preset"}), "presets 頂層"
    )
    version = data.get("schema_version")
    assert version == 1, f"presets: schema_version {version!r}（預期 1）"
    allow = data.get("allow_lists", {})
    _catalog_keys_ok(
        allow, frozenset({"harnesses", "requirements"}), "presets allow_lists"
    )
    for list_key in ("harnesses", "requirements"):
        values = allow.get(list_key)
        assert (
            isinstance(values, list)
            and values
            and all(isinstance(v, str) and v for v in values)
        ), f"presets: allow_lists.{list_key} 需非空字串清單"
        assert len(values) == len(set(values)), (
            f"presets: allow_lists.{list_key} 有重複值"
        )
    harness_vocab = frozenset(allow["harnesses"])
    requirement_vocab = frozenset(allow["requirements"])

    presets: dict[str, Preset] = {}
    for row in data.get("preset", []):
        _catalog_keys_ok(
            row,
            frozenset(
                {
                    "slug",
                    "requirement",
                    "harness",
                    "read_write",
                    "sandbox",
                    "background",
                    "default_binding",
                }
            ),
            "preset",
        )
        _catalog_required(
            row,
            ("slug", "requirement", "harness", "read_write", "sandbox", "background"),
            "preset",
        )
        slug = row["slug"]
        assert isinstance(slug, str) and slug, "presets: slug 需非空字串"
        assert slug not in presets, f"presets: duplicate slug {slug!r}"
        requirement = row["requirement"]
        assert requirement in requirement_vocab, (
            f"presets: preset {slug!r} unknown requirement {requirement!r}"
            f"（合法：{sorted(requirement_vocab)}）——legacy --map 相容 token"
        )
        harness = row["harness"]
        assert isinstance(harness, list) and harness, (
            f"presets: preset {slug!r} harness 需非空清單"
        )
        assert len(harness) == len(set(harness)), (
            f"presets: preset {slug!r} harness 有重複值"
        )
        for member in harness:
            assert member in harness_vocab, (
                f"presets: preset {slug!r} harness {member!r} 不在"
                f" allow_lists.harnesses（合法：{sorted(harness_vocab)}）"
            )
        read_write = row["read_write"]
        assert read_write in _PRESET_READ_WRITE, (
            f"presets: preset {slug!r} read_write {read_write!r} 不在詞彙"
            f"（合法：{sorted(_PRESET_READ_WRITE)}）"
        )
        sandbox = row["sandbox"]
        assert sandbox in _PRESET_SANDBOX, (
            f"presets: preset {slug!r} sandbox {sandbox!r} 不在詞彙"
            f"（合法：{sorted(_PRESET_SANDBOX)}）"
        )
        background = row["background"]
        assert isinstance(background, bool), (
            f"presets: preset {slug!r} background 需 bool"
        )
        default_binding = row.get("default_binding", {})
        assert isinstance(default_binding, dict), (
            f"presets: preset {slug!r} default_binding 需 table"
        )
        refs: dict[str, tuple[str, str | None]] = {}
        for member, entry in default_binding.items():
            assert member in harness, (
                f"presets: preset {slug!r} default_binding 宣告 {member!r} 但"
                f" harness membership 未含——membership 與 binding 需一致"
            )
            assert isinstance(entry, dict), (
                f"presets: preset {slug!r} default_binding.{member} 需 table"
            )
            _catalog_keys_ok(
                entry, frozenset({"ref", "effort"}), f"preset {slug} {member} binding"
            )
            _catalog_required(entry, ("ref",), f"preset {slug} {member} binding")
            ref = entry["ref"]
            assert isinstance(ref, str) and ref, (
                f"presets: preset {slug!r} default_binding.{member} ref 需非空字串"
            )
            effort = entry.get("effort")
            if effort is not None:
                assert effort in _EFFORT_ORDINAL, (
                    f"presets: preset {slug!r} effort token {effort!r} 不在跨家族"
                    f"詞彙（{sorted(_EFFORT_ORDINAL)}）"
                )
            refs[member] = (ref, effort)
        presets[slug] = Preset(
            slug, requirement, tuple(harness), read_write, sandbox, background, refs
        )
    assert presets, "presets: preset 清單不可為空"
    return presets


def load_presets(repo: Path) -> dict[str, Preset]:
    """讀取 repo 的 presets（缺檔＝FileNotFoundError——source of record 必在）。"""
    return parse_presets((repo / PRESET_SOURCE).read_text(encoding="utf-8"))


def resolve_deployment(
    catalog: ModelCatalog, presets: dict[str, Preset]
) -> dict[str, dict[str, tuple[DispatchBinding | None, str | None]]]:
    """preset default binding → (binding, deployment effort)；驗 FK／carrier／effort 形態。

    無 default binding 的 harness＝inherit ((None, None)——registry 檔無 model
    欄位，spawn-time 決定)。registry 投影只收 effort_encoding=field（zcode
    thoughtLevel 欄位）／param（CC spawn-time enum——frontmatter 僅 model）；
    slug_fixed／unsupported 是 bridge carrier 形態，非 registry 部署面。
    """
    resolved: dict[str, dict[str, tuple[DispatchBinding | None, str | None]]] = {}
    for slug, preset in sorted(presets.items()):
        per: dict[str, tuple[DispatchBinding | None, str | None]] = {}
        for member in preset.harness:
            entry = preset.default_binding.get(member)
            if entry is None:
                per[member] = (None, None)
                continue
            ref, effort = entry
            binding = catalog.bindings.get(ref)
            assert binding is not None, (
                f"presets: preset {slug!r} default_binding[{member}] 引用不存在的"
                f" binding {ref!r}"
            )
            carrier = _PRESET_HARNESS_CARRIERS.get(member)
            assert carrier is not None, (
                f"presets: harness {member!r} 無 registry carrier 對應"
                f"（已知：{sorted(_PRESET_HARNESS_CARRIERS)}）"
            )
            assert binding.carrier == carrier, (
                f"presets: preset {slug!r} default_binding[{member}]＝{ref!r} "
                f"carrier {binding.carrier!r} 與 harness {member!r}（{carrier!r}）"
                " 不相容"
            )
            if binding.effort_encoding == "field":
                assert effort is not None, (
                    f"presets: preset {slug!r} binding {ref!r} effort_encoding="
                    "field 需部署 effort（thoughtLevel）"
                )
                assert effort in binding.effort_values, (
                    f"presets: preset {slug!r} 部署 effort {effort!r} 不在 binding"
                    f" {ref!r} effort_values {list(binding.effort_values)}"
                    "——capability mismatch"
                )
            elif binding.effort_encoding == "param":
                assert effort is None, (
                    f"presets: preset {slug!r} binding {ref!r} effort_encoding=param"
                    "（spawn-time enum）——registry frontmatter 不帶 effort"
                )
            else:
                raise AssertionError(
                    f"presets: binding {ref!r} effort_encoding="
                    f"{binding.effort_encoding!r} 非 registry 部署形態"
                    "（slug_fixed／unsupported＝bridge carrier 面）"
                )
            per[member] = (binding, effort)
        resolved[slug] = per
    return resolved


_FRONTMATTER_ALLOWLIST = {"name", "description", "tools", "background"}


def split_frontmatter(role_name: str, role_body: str) -> tuple[str, str]:
    """前置驗證＋切分 frontmatter/body（BOM／缺 frontmatter／空 frontmatter 分別報）。"""
    if role_body.startswith("\ufeff"):
        raise AssertionError(f"{role_name}: frontmatter 前有 BOM——去掉後重存")
    if not role_body.startswith("---\n"):
        raise AssertionError(f"{role_name}: 缺 frontmatter（首行必須是 ---）")
    if role_body.startswith("---\n---\n"):
        raise AssertionError(
            f"{role_name}: frontmatter 為空（至少需 name/description）"
        )
    frontmatter, separator, body = role_body[4:].partition("\n---\n")
    if not separator:
        raise AssertionError(f"{role_name}: frontmatter 未閉合（缺 --- 結尾欄）")
    if not frontmatter.strip():
        raise AssertionError(
            f"{role_name}: frontmatter 為空（至少需 name/description）"
        )
    keys = {
        line.split(":", 1)[0].strip()
        for line in frontmatter.splitlines()
        if line.strip()
    }
    illegal = keys - _FRONTMATTER_ALLOWLIST
    if illegal:
        raise AssertionError(
            f"{role_name}: frontmatter 鍵 {sorted(illegal)} 超出白名單 "
            f"{sorted(_FRONTMATTER_ALLOWLIST)}（model/thoughtLevel 屬投影層——pins 由 sync 生成）"
        )
    return frontmatter, body


def project_tools(frontmatter: str, target: str) -> str:
    lines: list[str] = []
    for line in frontmatter.splitlines():
        if target == "claude" and line.startswith("tools:"):
            key, raw_tools = line.split(":", maxsplit=1)
            tools = [tool.strip() for tool in raw_tools.split(",")]
            tools = [
                tool for tool in tools if tool and not tool.startswith(CR_MCP_PREFIX)
            ]
            if not tools:
                raise AssertionError(
                    "claude 投影後 tools 全空（源 tools 只有 CR MCP 全名？）"
                    "—— CC 端語義未定義，先修 roles/ 源補非 CR tools"
                )
            line = f"{key}: {', '.join(tools)}"
        lines.append(line)
    return "\n".join(lines)


def render_registry(
    role_name: str,
    role_body: str,
    target: str,
    binding: DispatchBinding | None,
    effort: str | None,
) -> str:
    """投影 role 定義＋deployment binding（binding=None＝inherit——無 model 欄位）。

    zcode：effort_encoding=field → model＋thoughtLevel；claude：param → 僅
    model（CC effort＝spawn-time enum 非 frontmatter）。tools 的 CR MCP 剝除
    分歧由 project_tools 承載（不變）。
    """
    frontmatter, body = split_frontmatter(role_name, role_body)
    frontmatter = project_tools(frontmatter, target)
    target_fields = ""
    if binding is not None:
        if target == "zcode":
            target_fields = f"\nmodel: {binding.token}\nthoughtLevel: {effort}"
        else:
            target_fields = f"\nmodel: {binding.token}"
    return f"---\n{frontmatter}{target_fields}\n---\n{OWNERSHIP_MARKER}\n{body}"


def is_owned(file_text: str) -> bool:
    if not file_text.startswith("---\n"):
        return False
    _, separator, body = file_text[4:].partition("\n---\n")
    return bool(separator) and body.startswith(f"{OWNERSHIP_MARKER}\n")


def without_marker(file_text: str) -> str:
    return file_text.replace(f"{OWNERSHIP_MARKER}\n", "", 1)


def _role_background_declared(role_body: str) -> bool:
    frontmatter, _ = split_frontmatter("role", role_body)
    return any(line.strip() == "background: true" for line in frontmatter.splitlines())


def expected_projections(
    repo: Path,
    *,
    presets: dict[str, Preset] | None = None,
    catalog: ModelCatalog | None = None,
) -> dict[Path, str]:
    """roles＋presets＋catalog → 期望生成樹（單一機械投影路徑）。"""
    policy = load_presets(repo) if presets is None else presets
    cat = load_catalog(repo) if catalog is None else catalog
    roles = load_role_specs(repo)
    assert roles.keys() == policy.keys(), (
        f"roles/preset mismatch — roles-only: {sorted(set(roles) - set(policy))}, "
        f"preset-only: {sorted(set(policy) - set(roles))}"
    )
    resolved = resolve_deployment(cat, policy)
    expected: dict[Path, str] = {}
    for slug, preset in policy.items():
        declared = _role_background_declared(roles[slug])
        assert declared == preset.background, (
            f"preset {slug!r} background={preset.background} 但 roles frontmatter "
            f"{'有' if declared else '無'} background 宣告——deployment 與 authoring"
            " 需同步（parity gate）"
        )
        for harness in preset.harness:
            binding, effort = resolved[slug][harness]
            expected[repo / "agents" / harness / f"{slug}.md"] = render_registry(
                slug, roles[slug], harness, binding, effort
            )
    return expected


def inventory_owned_outputs(repo: Path) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for target in ("zcode", "claude"):
        for path in sorted((repo / "agents" / target).glob("*.md")):
            file_text = path.read_text(encoding="utf-8")
            if is_owned(file_text):
                outputs[path] = file_text
    return outputs


def compare_projection(
    expected: dict[Path, str],
    owned: dict[Path, str],
) -> list[Path]:
    paths = set(expected) | set(owned)
    return sorted(path for path in paths if expected.get(path) != owned.get(path))


def validate_collisions(
    expected: dict[Path, str],
    *,
    adopt_legacy: bool,
    legacy_paths: set[str] | None = None,
) -> None:
    allowlist = LEGACY_REVIEWER_OUTPUTS if legacy_paths is None else legacy_paths
    collisions = [
        path
        for path in expected
        if path.exists()
        and not is_owned(path.read_text(encoding="utf-8"))
        and (
            not adopt_legacy
            or "/".join(path.parts[-3:]) not in allowlist
            or without_marker(expected[path]) != path.read_text(encoding="utf-8")
        )
    ]
    assert not collisions, f"unmarked same-name outputs block sync: {collisions}"


def atomic_write(path: Path, file_text: str) -> None:
    """temp file + os.replace——撕裂中斷不留半損檔（marker 半損會卡死後續 sync）。"""
    fd, tmp_name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(file_text)
        os.replace(tmp_name, path)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def apply_projection(
    expected: dict[Path, str],
    owned: dict[Path, str],
    *,
    adopt_legacy: bool = False,
    legacy_paths: set[str] | None = None,
) -> None:
    validate_collisions(expected, adopt_legacy=adopt_legacy, legacy_paths=legacy_paths)
    for path, file_text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if owned.get(path) != file_text:
            atomic_write(path, file_text)
    for stale in set(owned) - set(expected):
        stale.unlink()


def render_map(
    expected: dict[Path, str],
    *,
    presets: dict[str, Preset],
    owned: dict[Path, str] | None = None,
    resolved: dict[str, dict[str, tuple[DispatchBinding | None, str | None]]]
    | None = None,
    catalog: ModelCatalog | None = None,
    verbose: bool = False,
) -> str:
    """role/requirement/zcode/claude 四欄（registry 欄反映磁碟現況——owned 導出）。

    verbose 追加 preset／binding／model identity／token kind／capabilities 欄
    （--map --verbose 導航用；requirement 欄＝presets 的 legacy 相容 token）。
    """
    on_disk = (
        {(path.parent.name, path.stem) for path in owned}
        if owned is not None
        else {(path.parent.name, path.stem) for path in expected}
    )
    header = "role\trequirement\tzcode\tclaude"
    if verbose:
        assert resolved is not None and catalog is not None, (
            "render_map(verbose=True) 需 resolved 與 catalog（main --map --verbose 提供）"
        )
        header += (
            "\tpreset.zcode_binding\tpreset.zcode_model\tpreset.zcode_effort"
            "\tpreset.zcode_token_kind\tpreset.zcode_model_identity"
            "\tpreset.claude_binding\tpreset.claude_model\tpreset.claude_effort"
            "\tpreset.claude_token_kind\tpreset.claude_model_identity"
            "\tmodel_capabilities"
        )
    rows = [header]
    for role in sorted(presets):
        preset = presets[role]
        zcode = "yes" if ("zcode", role) in on_disk else "no"
        claude = "yes" if ("claude", role) in on_disk else "no"
        row = f"{role}\t{preset.requirement}\t{zcode}\t{claude}"
        if verbose:
            assert resolved is not None and catalog is not None, (
                "render_map(verbose=True) 需 resolved 與 catalog（main --map --verbose 提供）"
            )
            cells = [row]
            for member in ("zcode", "claude"):
                binding, effort = resolved[role][member]
                cells.extend(
                    (
                        binding.id if binding else "inherit",
                        binding.token if binding else "-",
                        effort if effort else "-",
                        binding.token_kind if binding else "-",
                        binding.model_identity if binding else "-",
                    )
                )
            caps = sorted(
                f"{mid}:{cap.name}"
                for mid in sorted(
                    {
                        b.model_identity
                        for b, _ in resolved[role].values()
                        if b is not None
                    }
                )
                for cap in catalog.identities[mid].capabilities
            )
            cells.append(",".join(caps) if caps else "-")
            row = "\t".join(cells)
        rows.append(row)
    return "\n".join(rows)


_MODES = {"check", "map", "sync", "adopt-legacy"}


def main(
    repo: Path,
    *,
    mode: str,
    legacy_paths: set[str] | None = None,
    verbose: bool = False,
) -> int:
    """exit 語義：0=綠、1=drift（生成物 vs 源，重跑 sync 可修）、2=fatal
    （presets／catalog 缺席或 schema 違規／roles-preset mismatch／binding
    不相容——修源重跑，sync 修不了）。"""
    assert mode in _MODES, f"unknown mode: {mode}（合法：{sorted(_MODES)}）"
    try:
        catalog = load_catalog(repo)
        presets = load_presets(repo)
    except FileNotFoundError as exc:
        print(f"fatal (source missing): {exc}", file=sys.stderr)
        return 2
    except AssertionError as exc:
        print(f"fatal (presets/catalog schema): {exc}", file=sys.stderr)
        return 2
    try:
        expected = expected_projections(repo, presets=presets, catalog=catalog)
    except AssertionError as exc:
        print(f"fatal (roles/preset mismatch): {exc}", file=sys.stderr)
        return 2
    owned = inventory_owned_outputs(repo)
    drift = compare_projection(expected, owned)
    if mode == "check":
        for path in drift:
            print(path)
        return 1 if drift else 0
    if mode == "map":
        resolved = resolve_deployment(catalog, presets)
        print(
            render_map(
                expected,
                presets=presets,
                owned=owned,
                resolved=resolved,
                catalog=catalog,
                verbose=verbose,
            )
        )
        return 0
    apply_projection(
        expected, owned, adopt_legacy=mode == "adopt-legacy", legacy_paths=legacy_paths
    )
    return 0


